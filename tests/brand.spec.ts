import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
mkdirSync('docs/qa/brand', { recursive: true });

test('brand first view runs a real engine under CSP and enters the independent lab', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const response = await page.goto('/');
  expect(response!.headers()['content-security-policy']).toContain("script-src 'self';");
  expect(response!.headers()['content-security-policy']).not.toContain("'unsafe-eval'");
  await expect(page.getByTestId('brand-page')).toBeVisible();
  await expect(page.getByTestId('game-lab')).toHaveCount(0);
  expect(await page.evaluate(() => localStorage.getItem('snake-lab-play-v1'))).toBeNull();
  expect(page.workers()).toHaveLength(0);
  const hero = page.locator('.brand-hero .brand-live');
  await expect(hero.locator('svg')).toBeInViewport({ratio:0.6});
  await expect(hero).toHaveAttribute('data-running', 'true');
  await expect(hero).not.toHaveAttribute('data-steps', '0');
  await hero.getByRole('button', { name: '暂停实时演示', exact: true }).click();
  const step = await hero.getAttribute('data-steps');
  await page.waitForTimeout(200);
  expect(await hero.getAttribute('data-steps')).toBe(step);
  await hero.getByRole('button', { name: '继续实时演示', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(await page.locator('video[src]').count()).toBe(0);
  await page.evaluate(() => window.scrollTo(0, 0));
  mkdirSync('docs/qa/brand', { recursive: true });
  await page.screenshot({ path: `docs/qa/brand/${test.info().project.name}-hero.png` });
  await page.screenshot({ path: `docs/qa/brand/${test.info().project.name}-page.png`, fullPage: true });
  await page.getByRole('link', { name: '进入实验室', exact: false }).first().click();
  await expect(page).toHaveURL(/#\/lab$/);
  await expect(page.getByTestId('game-lab')).toBeVisible();
  await expect(page.locator('canvas')).toHaveCount(1);
  await expect(page.getByLabel('决策策略', { exact: true })).toHaveValue('hamiltonian-shortcut');
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await page.getByLabel('决策策略', { exact: true }).selectOption('bfs');
  await page.goto('/');
  await page.getByRole('link', { name: '进入实验室', exact: false }).first().click();
  await expect(page.getByLabel('决策策略', { exact: true })).toHaveValue('bfs');
  await expect(page.getByRole('button', { name: '开始运行', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByTestId('game-lab')).toBeVisible();
  expect(errors).toEqual([]);
});

test('real videos load lazily, play, pause outside the viewport and retain explicit pause', async ({ page }) => {
  await page.goto('/');
  const film = page.locator('.film-arena');
  const video = film.locator('video');
  await expect(video).not.toHaveAttribute('src', /webm/);
  await film.scrollIntoViewIfNeeded();
  await expect(video).toHaveAttribute('src', '/media/arena.webm');
  await expect.poll(() => video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(0.2);
  expect(await video.evaluate(element => ({ muted: (element as HTMLVideoElement).muted, inline: (element as HTMLVideoElement).playsInline, loop: (element as HTMLVideoElement).loop }))).toEqual({ muted: true, inline: true, loop: true });
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', {configurable:true,value:true}); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(video).toHaveJSProperty('paused', true);
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', {configurable:true,value:false}); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(video).toHaveJSProperty('paused', false);
  await film.getByRole('button', { name: '暂停策略竞技视频' }).click();
  await expect(video).toHaveJSProperty('paused', true);
  await page.locator('.brand-hero').scrollIntoViewIfNeeded();
  await film.scrollIntoViewIfNeeded();
  await expect(video).toHaveJSProperty('paused', true);
  await film.getByRole('button', { name: '播放策略竞技视频' }).click();
  await expect(video).toHaveJSProperty('paused', false);
  await page.locator('.brand-final').scrollIntoViewIfNeeded();
  await expect(video).toHaveJSProperty('paused', true);
  await expect(page.locator('.brand-live[data-running="true"]')).toHaveCount(0);
  const shortcut = page.locator('.film-shortcut');
  await shortcut.scrollIntoViewIfNeeded();
  await expect.poll(() => shortcut.locator('video').evaluate(element => (element as HTMLVideoElement).currentTime)).toBeGreaterThan(0.2);
  const metadata = await page.locator('video').evaluateAll(elements => elements.map(element => ({ source: element.getAttribute('src'), width: (element as HTMLVideoElement).videoWidth, height: (element as HTMLVideoElement).videoHeight, ready: (element as HTMLVideoElement).readyState })));
  await page.screenshot({ path: `docs/qa/brand/${test.info().project.name}-cinema.png` });
  writeFileSync(`docs/qa/brand/${test.info().project.name}-media.json`, JSON.stringify(metadata, null, 2));
  await film.getByRole('link').click();
  await expect(page).toHaveURL(/#\/arena$/);
  await expect(page.getByTestId('arena-lab')).toBeVisible();
});

test('reduced motion and failed media retain an accessible poster', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const hero = page.locator('.brand-hero .brand-live');
  await expect(hero).toHaveAttribute('data-steps', '0');
  await hero.scrollIntoViewIfNeeded();
  await page.waitForTimeout(150);
  await expect(hero).toHaveAttribute('data-steps', '0');
  await page.locator('.film-arena').scrollIntoViewIfNeeded();
  await expect(page.locator('video[src]')).toHaveCount(0);
  await expect(page.locator('.film-arena img')).toBeVisible();
  await page.route('**/media/*.webm', route => route.abort());
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await expect(page.locator('.film-arena')).toContainText('视频暂不可用');
  await expect(page.locator('.film-arena img')).toBeVisible();
  await page.locator('.film-arena a').click();
  await expect(page.getByTestId('arena-lab')).toBeVisible();
});

test('strategy examples, module CTAs, legacy lesson links and browser back work', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('tab', { name: /A\* 搜索/ }).click();
  await expect(page.getByRole('tabpanel')).toContainText('检查退路');
  await page.getByRole('tab', { name: /A\* 搜索/ }).press('ArrowRight');
  await expect(page.getByRole('tab', { name: /纯贪心/ })).toBeFocused();
  await page.getByRole('tab', { name: /纯贪心/ }).press('ArrowLeft');
  const board = page.locator('.brand-strategy-board .brand-live');
  await board.getByRole('button', { name: '演示前进一步' }).click();
  await expect(board).toHaveAttribute('data-steps', '1');
  await page.getByRole('tab', { name: /纯贪心/ }).click();
  await expect(board).toHaveAttribute('data-steps', '0');
  await page.getByRole('link', { name: '打开 A* 课堂预览' }).click();
  await expect(page).toHaveURL(/#\/lessons\/astar$/);
  await expect(page.getByTestId('brand-page')).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: /A\*/ }).first()).toBeVisible();
  await page.goBack();
  await expect(page.getByTestId('brand-page')).toBeVisible();
  await page.getByRole('link', { name: /让策略从经验中学习/ }).click();
  await expect(page).toHaveURL(/#\/training$/);
  await expect(page.getByRole('heading', { name: '从经验中学习，让策略成长' })).toBeVisible();
});
